"""Explicitly refresh the C++ project's assets/fonts from the Python reference.
Run from any directory: python src_c/scripts/sync_assets.py
Never copies private settings.toml. Build does not depend on the Python tree.
"""
import ast
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "src"

def table(path, name):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return ast.literal_eval(node.value)
    raise ValueError(name)

def sync():
    for folder in ("faces", "transitions", "static"):
        shutil.copytree(SOURCE / folder, ROOT / "data" / folder, dirs_exist_ok=True)
    shutil.copyfile(SOURCE / "settings.example.toml", ROOT / "settings.example.toml")
    oled = table(SOURCE / "I2C_sim.py", "_FONT_5X7")
    face = table(SOURCE / "emotes.py", "FONT_5X7")
    out = ["// Generated by scripts/sync_assets.py; original project font tables.",
           "#pragma once", "#include <cstdint>", "namespace proto {",
           "inline const uint8_t* oledGlyph(char c) { switch(c) {"]
    for char, cols in oled.items():
        out.append("case %d: { static const uint8_t v[]={%s}; return v; }" %
                   (ord(char), ",".join(map(str, cols))))
    out += ["default: return oledGlyph('?'); }}",
            "inline const uint8_t* faceGlyph(uint8_t c) { switch(c) {"]
    for char, rows in face.items():
        out.append("case %d: { static const uint8_t v[]={%s}; return v; }" %
                   (ord(char), ",".join(str(int(r, 2)) for r in rows)))
    out += ["default: { static const uint8_t v[7]={}; return v; } }}", "}"]
    (ROOT / "include" / "fonts.h").write_text("\n".join(out)+"\n", encoding="utf-8")
    print("Copied public assets and exact font tables; private settings unchanged.")

if __name__ == "__main__":
    sync()
